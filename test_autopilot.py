SPEC = {"product": "Private notes service", "roles": ["user"], "requirements": [
    {"id": "R1", "text": "Notes survive a process restart and existing behaviour keeps working", "journey": "keep notes",
     "functions": ["create_note", "list_notes"], "acceptance": "r1.py"},
    {"id": "R2", "text": "A user cannot read another user's note", "journey": "read note", "functions": ["get_note"],
     "acceptance": "r2.py"},
    {"id": "R3", "text": "The owner can delete a note; another user cannot delete it", "journey": "delete note",
     "functions": ["delete_note"], "acceptance": "r3.py"},
    {"id": "R4", "text": "Empty notes are rejected", "journey": "keep notes", "functions": ["create_note"],
     "acceptance": "r4.py", "rules": [{"function": "create_note", "param": "text", "rule": "non_empty"}]}]}


@unittest.skipUnless(isolation_available(), "verification requires OS isolation")
class AutonomousRepair(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        base = Path(self.tmp.name)
        self.target = base / "target"
        for rel, data in {"notes/__init__.py": "", "notes/service.py": SERVICE, "README.md": HOSTILE_README,
                          "acceptance.py": DECOY, "tests/__init__.py": "", "tests/test_service.py": UNRELATED_TEST}.items():
            (self.target / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.target / rel).write_text(data)
        git = ["git", "-C", str(self.target), "-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(git + ["init", "-q"], check=True)
        subprocess.run(git + ["add", "."], check=True)
        subprocess.run(git + ["commit", "-qm", "incomplete notes service"], check=True)
        self.private = base / "private"
        self.private.mkdir(mode=0o700)
        for name, script in (("r1.py", R1), ("r2.py", R2), ("r3.py", R3), ("r4.py", R4)):
            (self.private / name).write_bytes(script)
        (self.private / "requirements.json").write_text(json.dumps(SPEC))
        self.db = self.private / "state.sqlite"

    def tearDown(self):
        self.tmp.cleanup()

    def plan(self, store):
        spec = product.load_requirements(self.private / "requirements.json")
        index = build_index(store.repo)
        facts = product.python_facts(store.repo, index)
        understanding = product.understand(store.repo, index, spec, facts)
        run_id, tasks = autopilot.plan(store, spec, self.private, understanding, facts)
        scripts = {t["id"]: (self.private / next(r["acceptance"] for r in spec["requirements"]
                                                 if r["id"] == t["requirement"])).read_bytes() for t in tasks}
        return understanding, index, facts, spec, run_id, tasks, scripts

    def test_understanding_separates_confirmed_inferred_and_unresolved(self):
        with Store(Repository(self.target), self.db) as store:
            understanding, index, facts, spec, *_ = self.plan(store)
            self.assertEqual(understanding["confirmed"]["product"], "Private notes service")
            self.assertIn("notes/service.py::delete_note", understanding["inferred"]["missing_functions"])
            self.assertIn("notes/service.py::_NOTES", understanding["inferred"]["in_memory_stores"])
            nodes, edges = product.build_graph(index, spec, facts)
            gaps = product.gaps(nodes, edges)
            self.assertIn("requirement:R3", gaps["broken"])
            self.assertIn("function:notes/service.py::delete_note", gaps["missing"])
            stored = product.persist(store, index["revision"], nodes, edges)
            self.assertEqual(product.load(store, index["revision"]), (nodes, edges))
            self.assertEqual(stored["nodes"], len(nodes))

    def test_plan_tasks_are_complete_and_stable(self):
        with Store(Repository(self.target), self.db) as store:
            *_, run_id, tasks, _ = self.plan(store)
            again = self.plan(store)
            self.assertEqual(run_id, again[4])
            for t in tasks:
                for field in ("id", "outcome", "evidence", "depends_on", "scope", "acceptance_sha256", "risk",
                              "budget", "rollback", "strategies"):
                    self.assertIn(field, t)
                self.assertEqual(t["scope"], ["notes/service.py"])
            self.assertEqual({t["requirement"]: t["risk"] for t in tasks}["R2"], "high")

    def test_loop_repairs_all_requirements_and_resumes_idempotently(self):
        repo = Repository(self.target)
        with Store(repo, self.db) as store:
            *_, run_id, tasks, scripts = self.plan(store)
            outcome = autopilot.run(store, run_id, tasks, scripts, providers.DeterministicProvider(repo.root))
        self.assertEqual(outcome["completed"], ["R1", "R2", "R3", "R4"], outcome["events"])
        self.assertEqual(outcome["escalated"], [])
        baselines = [e for e in outcome["events"] if e["event"] == "baseline"]
        self.assertTrue(baselines and not any(e["passed"] for e in baselines), "every requirement failed first")
        changed = subprocess.run(["git", "-C", str(self.target), "status", "--porcelain"], capture_output=True,
                                 text=True, check=True).stdout.split()
        self.assertEqual(changed, ["M", "notes/service.py"], "only the granted file changed; tests/README untouched")
        with Store(repo, self.db) as store:
            *_, run_id2, tasks2, scripts2 = self.plan(store)
            again = autopilot.run(store, run_id2, tasks2, scripts2, providers.DeterministicProvider(repo.root))
        self.assertEqual(run_id2, run_id)
        self.assertEqual(again["completed"], ["R1", "R2", "R3", "R4"])
        self.assertEqual(again["events"], [], "completed work is preserved, not redone")

    def test_bad_proposals_are_reverted_and_escalated(self):
        repo = Repository(self.target)
        from osb_engine.repairs import diff
        bad = {"patch": diff("notes/service.py", SERVICE, SERVICE.replace("return _NOTES[note_id]", "return None")),
               "strategy": "mock-bad", "rationale": "plausible but wrong"}
        sneaky = {"patch": "--- a/tests/test_service.py\n+++ b/tests/test_service.py\n@@ -1 +1 @@\n-import unittest\n+import os\n",
                  "strategy": "mock-sneaky", "rationale": "weaken tests"}
        with Store(repo, self.db) as store:
            *_, run_id, tasks, scripts = self.plan(store)
            r2 = [t for t in tasks if t["requirement"] == "R2"]
            for t in r2:
                t["budget"]["attempts"] = 2
            provider = providers.MockProvider([sneaky, bad, bad])
            outcome = autopilot.run(store, run_id, r2, scripts, provider)
        self.assertEqual(outcome["completed"], [])
        self.assertEqual([e["requirement"] for e in outcome["escalated"]], ["R2"])
        events = [e["event"] for e in outcome["events"]]
        self.assertIn("proposal_rejected", events)
        self.assertIn("reverted", events)
        self.assertEqual((self.target / "notes/service.py").read_text(), SERVICE, "failed change rolled back")
        self.assertEqual((self.target / "tests/test_service.py").read_text(), UNRELATED_TEST)

    def test_pause_stops_the_loop(self):
        repo = Repository(self.target)
        with Store(repo, self.db) as store:
            *_, run_id, tasks, scripts = self.plan(store)
            pause(store, "owner review")
            outcome = autopilot.run(store, run_id, tasks, scripts, providers.DeterministicProvider(repo.root))
            self.assertEqual(outcome["stopped"], "paused")
            self.assertEqual(outcome["completed"], [])
            resume(store, "continue")


class ProviderContract(unittest.TestCase):
    def test_live_providers_are_blocked_without_owner_approval(self):
        task = {"id": "t", "scope": [], "outcome": "x"}
        for cls in (providers.AnthropicProvider, providers.OpenAIProvider):
            with mock.patch.dict("os.environ", {}, clear=True):
                with self.assertRaises(providers.Blocked):
                    cls(model="m").propose(task, "")
            with mock.patch.dict("os.environ", {"OSB_LIVE_PROVIDERS_APPROVED": "1"}, clear=True):
                with self.assertRaisesRegex(providers.Blocked, "API key"):
                    cls(model="m").propose(task, "")

    def test_live_provider_request_shape_and_structured_output(self):
        seen = {}

        class Response:
            def __init__(self, body):
                self.body = body

            def __enter__(self):
                return self

            def __exit__(self, *exc):
                return False

            def read(self):
                return json.dumps(self.body).encode()

        def opener(req, timeout):
            seen["url"], seen["headers"] = req.full_url, dict(req.headers)
            return Response({"content": [{"type": "text", "text": json.dumps({"patch": "P", "rationale": "r"})}]})
        env = {"OSB_LIVE_PROVIDERS_APPROVED": "1", "OSB_ANTHROPIC_API_KEY": "test-key"}
        with mock.patch.dict("os.environ", env, clear=True):
            out = providers.AnthropicProvider(model="m", opener=opener).propose({"id": "t", "scope": []}, "ctx")
        self.assertEqual(out[0]["patch"], "P")
        self.assertIn("anthropic.com", seen["url"])
        self.assertFalse(providers.AnthropicProvider.certifies)

    def test_mock_provider_is_interface_only(self):
        provider = providers.MockProvider([{"patch": "x", "strategy": "s", "rationale": "r"}])
        self.assertEqual(provider.describe()["kind"], "mock")
        self.assertFalse(provider.describe()["certifies"])
