"""S06 acceptance: OSB repairs an incomplete application through its own loop, verified externally.

The owner requirements and their external acceptance scripts below are fixed before the loop
runs. Repairs are generated by OSB's deterministic provider (not by the test), applied through
the kernel and judged only by kernel-replayed external acceptance.
"""
